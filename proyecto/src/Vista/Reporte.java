    /** Los 5 reportes salen de la base de datos (pkg_reporte); cada botón abre uno en una tabla. */
    private void configurar() {
        setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
        jLabel2.setText("");                 // el diseño dejó "jLabel2" escrito junto al logo
        jLabel6.setText("SUPERVISOR");       // el diseño decía ENCUESTADOR

        btnReporte1.setText("1. " + ReporteDAO.TITULOS[0]);
        Btnreporte2.setText("2. " + ReporteDAO.TITULOS[1]);
        BtnReporte3.setText("3. " + ReporteDAO.TITULOS[2]);
        btnreporte4.setText("4. " + ReporteDAO.TITULOS[3]);
        btnreporte5.setText("5. " + ReporteDAO.TITULOS[4]);

        btnReporte1.addActionListener(e -> abrirReporte(1));
        Btnreporte2.addActionListener(e -> abrirReporte(2));
        BtnReporte3.addActionListener(e -> abrirReporte(3));
        btnreporte4.addActionListener(e -> abrirReporte(4));
        btnreporte5.addActionListener(e -> abrirReporte(5));
        BtnVolver.addActionListener(e -> dispose());

        setLocationRelativeTo(null);
    }

    /** Pide el reporte a la base de datos y lo muestra. */
    private void abrirReporte(int numero) {
        try {
            ResultadoReporte resultado = dao.generar(numero);
            new VentanaReporte(this, resultado).setVisible(true);
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo generar el reporte:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

