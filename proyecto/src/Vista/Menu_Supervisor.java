    /** Botones sin acción en el diseño, y cierre de la ventana. */
    private void configurarNavegacion() {
        setLocationRelativeTo(null);
        BtnRevisados.addActionListener(e -> abrir(() -> new Revisados()));
        BtnReportes.addActionListener(e -> abrir(() -> new Reporte()));
        // Cerrar la ventana con la X cierra la aplicación: antes se cierra la sesión en la base de datos
        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosing(java.awt.event.WindowEvent e) {
                Sesion.cerrar();
            }
        });
    }

    /**
     * Abre otra ventana del supervisor y oculta este menú; al cerrar esa ventana el menú vuelve a aparecer.
     * Si la ventana falla al construirse, se muestra el motivo y el menú sigue visible.
     */
    private void abrir(java.util.function.Supplier<javax.swing.JFrame> fabrica) {
        try {
            final javax.swing.JFrame ventana = fabrica.get();
            ventana.setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
            ventana.setLocationRelativeTo(null);
            ventana.addWindowListener(new java.awt.event.WindowAdapter() {
                @Override
                public void windowClosed(java.awt.event.WindowEvent e) {
                    setVisible(true);
                }
            });
            setVisible(false);
            ventana.setVisible(true);
        } catch (Throwable ex) {
            setVisible(true);
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo abrir la pantalla:\n" + ex,
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** VOLVER: cierra la sesión (en la base de datos y en la aplicación) y regresa al Login. */
    private void cerrarSesion() {
        Sesion.cerrar();
        new Login().setVisible(true);
        dispose();
    }

