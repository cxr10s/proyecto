    /** Vuelve a leer las comidas del hogar y las muestra en la tabla. */
    public void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        if (idHogar == null) {
            return;
        }
        boolean conFecha = modelo.findColumn("Fecha") >= 0;
        try {
            List<ComidaFuera> comidas = dao.listar(idHogar);
            for (ComidaFuera c : comidas) {
                List<Object> fila = new ArrayList<>(Arrays.asList(
                    c.getNumOrden(),
                    c.getDescripcion(),
                    ComidaFuera.DESAYUNO.equals(c.getTipoComida()) ? "X" : "",
                    ComidaFuera.ALMUERZO.equals(c.getTipoComida()) ? "X" : "",
                    ComidaFuera.CENA.equals(c.getTipoComida()) ? "X" : "",
                    ComidaFuera.ONCES.equals(c.getTipoComida()) ? "X" : "",
                    c.getCantidad(),
                    c.getNombreForma(),
                    c.getNombreLugar(),
                    String.format(new Locale("es", "CO"), "$ %,d", c.getCosto()),
                    c.getNombreFrecuencia(),
                    c.getTipoGasto(),
                    c.isDomicilio() ? "X" : ""));
                if (conFecha) {
                    fila.add(1, "");    // celda de la columna "Fecha" (oculta)
                }
                modelo.addRow(fila.toArray());
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar las comidas:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Abre el formulario: numOrdenEditar null = agregar; con valor = modificar. */
    private void abrirFormulario(String numOrdenEditar) {
        if (idHogar == null) {
            JOptionPane.showMessageDialog(this, "Abra esta ventana desde un hogar.",
                    "Comidas fuera del hogar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            AgregarDatosComidasPreparadasFuera form =
                    new AgregarDatosComidasPreparadasFuera(this, idHogar, numOrdenEditar);
            setVisible(false);      // al cerrar el formulario, él mismo vuelve a mostrar esta ventana
            form.setVisible(true);
        } catch (Throwable ex) {    // si el formulario falla al construirse, que se vea el motivo
            setVisible(true);
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudo abrir el formulario de comidas fuera del hogar:\n" + ex,
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void modificarSeleccionado() {
        int fila = jTable1.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione una comida de la tabla para modificarla.",
                    "Modificar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        abrirFormulario(String.valueOf(jTable1.getValueAt(fila, 0)));   // columna NUMERO DE ORDEN
    }

    /** Elimina la comida seleccionada (con confirmación). */
    private void eliminarSeleccionado() {
        int fila = jTable1.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione una comida de la tabla para eliminarla.",
                    "Eliminar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String numOrden = String.valueOf(jTable1.getValueAt(fila, 0));

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Seguro que desea eliminar la comida " + numOrden + " del hogar " + idHogar + "?\n"
                + "Esta acción no se puede deshacer.",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idHogar, Integer.parseInt(numOrden));
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Comida " + numOrden + " eliminada correctamente.");
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo eliminar:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

