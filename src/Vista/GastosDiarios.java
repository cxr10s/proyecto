    /** Vuelve a leer los gastos del hogar y los muestra en la tabla. */
    public void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tab_Datos.getModel();
        modelo.setRowCount(0);
        if (idHogar == null) {
            return;
        }
        try {
            List<GastoDiario> gastos = dao.listar(idHogar);
            for (GastoDiario g : gastos) {
                modelo.addRow(new Object[]{
                    g.getNumOrden(),
                    g.getFecha() == null ? "" : g.getFecha().format(FECHA),
                    g.getNombreArticulo(),
                    g.getNombreMedida(),
                    g.getEquivalencia(),
                    g.getNombreForma(),
                    g.getNombreLugar(),
                    String.format(new Locale("es", "CO"), "$ %,d", g.getCosto()),
                    g.getNombreFrecuencia(),
                    g.getTipoGasto()
                });
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar los gastos:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Abre el formulario: numOrdenEditar null = agregar; con valor = modificar. */
    private void abrirFormulario(String numOrdenEditar) {
        if (idHogar == null) {
            JOptionPane.showMessageDialog(this, "Abra esta ventana desde un hogar.",
                    "Gastos diarios", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            AgregarDatosGastosDiarios form = new AgregarDatosGastosDiarios(this, idHogar, numOrdenEditar);
            setVisible(false);      // al cerrar el formulario, él mismo vuelve a mostrar esta ventana
            form.setVisible(true);
        } catch (Throwable ex) {    // si el formulario falla al construirse, que se vea el motivo
            setVisible(true);
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudo abrir el formulario de gastos diarios:\n" + ex,
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void modificarSeleccionado() {
        int fila = tab_Datos.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un gasto de la tabla para modificarlo.",
                    "Modificar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        abrirFormulario(String.valueOf(tab_Datos.getValueAt(fila, 0)));   // columna NUMERO DE ORDEN
    }

    /** Elimina el gasto seleccionado (con confirmación). */
    private void eliminarSeleccionado() {
        int fila = tab_Datos.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un gasto de la tabla para eliminarlo.",
                    "Eliminar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String numOrden = String.valueOf(tab_Datos.getValueAt(fila, 0));

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Seguro que desea eliminar el gasto " + numOrden + " del hogar " + idHogar + "?\n"
                + "Esta acción no se puede deshacer.",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idHogar, Integer.parseInt(numOrden));
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Gasto " + numOrden + " eliminado correctamente.");
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo eliminar:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Cerrar esta ventana no cierra la aplicación: VOLVER y la X regresan a Hogar. */
    private void configurarNavegacion() {
        setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
        setLocationRelativeTo(null);
        if (idHogar != null) {
            setTitle("Gastos diarios - Hogar " + idHogar);
        }
        BtnVolver.addActionListener(e -> dispose());
        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                if (padre != null) {
                    padre.setVisible(true);
                }
            }
        });
    }

