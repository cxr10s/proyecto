    /** Vuelve a leer de la base de datos los alimentos y los valores de mercado del hogar. */
    public void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) TabDatos.getModel();
        modelo.setRowCount(0);
        actuales = new ArrayList<>();
        if (idHogar == null) {
            return;
        }
        try {
            actuales = dao.listar(idHogar);
            for (CaracteristicaGasto g : actuales) {
                int f = g.getFrecuencia();
                modelo.addRow(new Object[]{
                    g.getNombreAlimento(),
                    (f >= 0 && f < CaracteristicaGasto.FREC_NOMBRES.length) ? CaracteristicaGasto.FREC_NOMBRES[f] : "",
                    g.getValorUltimaCompra() == null ? ""
                            : String.format(new Locale("es", "CO"), "$ %,d", g.getValorUltimaCompra()),
                    CaracteristicaGasto.NO_APLICA.equals(g.getComprara()) ? "" : g.getComprara()
                });
            }
            cargarMercados();
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar los datos:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /** Pone en jTable2 el valor guardado de cada mercado ("$" si todavía no tiene). */
    private void cargarMercados() throws SQLException {
        Map<String, Long> valores = mercadoDao.listar(idHogar);
        DefaultTableModel m = (DefaultTableModel) TabPequena.getModel();
        for (int i = 0; i < m.getRowCount(); i++) {
            Long v = valores.get(String.valueOf(m.getValueAt(i, 0)));
            m.setValueAt(v == null ? "$" : String.format(new Locale("es", "CO"), "$ %,d", v), i, 2);
        }
    }

    /** Abre el formulario: codigoEditar null = agregar; con valor = modificar ese alimento. */
    private void abrirFormulario(String codigoEditar) {
        if (idHogar == null) {
            JOptionPane.showMessageDialog(this, "Abra esta ventana desde un hogar.",
                    "Características del gasto", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            AgregardatosCaracteristicas form = new AgregardatosCaracteristicas(this, idHogar, codigoEditar);
            setVisible(false);      // al cerrar el formulario, él mismo vuelve a mostrar esta ventana
            form.setVisible(true);
        } catch (Throwable ex) {    // si el formulario falla al construirse, que se vea el motivo
            setVisible(true);
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudo abrir el formulario de características del gasto:\n" + ex,
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private CaracteristicaGasto seleccionado(String accion, String articulo) {
        int fila = TabDatos.getSelectedRow();
        if (fila < 0 || fila >= actuales.size()) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un alimento de la tabla para " + accion + ".",
                    articulo, JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return actuales.get(fila);
    }

    private void modificarSeleccionado() {
        CaracteristicaGasto g = seleccionado("modificarlo", "Modificar");
        if (g != null) {
            abrirFormulario(g.getCodigoAlimento());
        }
    }

    /** Elimina el alimento seleccionado (con confirmación). */
    private void eliminarSeleccionado() {
        CaracteristicaGasto g = seleccionado("eliminarlo", "Eliminar");
        if (g == null) {
            return;
        }
        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Seguro que desea eliminar este alimento del hogar " + idHogar + "?\n"
                + g.getNombreAlimento() + "\nEsta acción no se puede deshacer.",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idHogar, g.getCodigoAlimento());
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Alimento eliminado correctamente.");
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo eliminar:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

