    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Comprobar que se haya seleccionado un mercado
    if (ComboMercado.getSelectedIndex() == 0) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Debe seleccionar un mercado.",
            "Dato incompleto",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        ComboMercado.requestFocus();
        return;
    }

    // Obtener el valor del JSpinner
    int valor = (Integer) spinnerValorMercado.getValue();

    // Comprobar que el valor sea mayor que 0
    if (valor <= 0) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Debe ingresar un valor mayor que 0.",
            "Dato incompleto",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        spinnerValorMercado.requestFocus();
        return;
    }

    // Obtener el mercado seleccionado
    // Obtener el mercado seleccionado
    // Guardar en la base de datos (si no se puede, no se actualiza la tabla)
    if (idHogar != null) {
        try {
            mercadoDao.guardar(idHogar, ID_MERCADO[ComboMercado.getSelectedIndex() - 1], valor);
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo guardar el mercado:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
    }

    String mercado = ComboMercado.getSelectedItem().toString();

    // Obtener el modelo de la tabla
    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) TabPequena.getModel();

    // Buscar el mercado en la tabla y actualizar su precio
    boolean encontrado = false;

    for (int i = 0; i < modelo.getRowCount(); i++) {

        String mercadoTabla = modelo.getValueAt(i, 1).toString();

        if (mercadoTabla.equals(mercado)) {

            // Actualizar únicamente la columna del precio
            modelo.setValueAt(String.format(new Locale("es", "CO"), "$ %,d", valor), i, 2);

            encontrado = true;
            break;
        }
    }

    // Si no existe en la tabla, mostrar un mensaje
    if (!encontrado) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se encontró el mercado seleccionado en la tabla.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Limpiar campos
    ComboMercado.setSelectedIndex(0);
    spinnerValorMercado.setValue(0);

    // Ocultar el formulario de ingreso
    ComboMercado.setVisible(false);
    spinnerValorMercado.setVisible(false);
    btnGuardar.setVisible(false);
    jLabel2.setVisible(false);
    jLabel3.setVisible(false);

    // Mensaje de confirmación
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "El mercado fue agregado correctamente.",
        "Registro exitoso",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_btnGuardarActionPerformed

