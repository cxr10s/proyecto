    /** Llena el formulario con los datos de la visita (modo modificar). */
    private void cargarDatos() {
        try {
            ControlVisita v = dao.buscar(idHogar, Integer.parseInt(numVisitaEditar));
            if (v == null) {
                JOptionPane.showMessageDialog(this, "No se encontró la visita " + numVisitaEditar + ".",
                        "Error", JOptionPane.ERROR_MESSAGE);
                javax.swing.SwingUtilities.invokeLater(this::dispose);
                return;
            }
            Dap_fechavisita.setDate(v.getFecha());
            Tmp_iniciovisita.setTime(v.getHoraInicio());
            Cob_inciovisita.setSelectedItem(v.getJornadaInicio());
            Tmp_finvisita.setTime(v.getHoraFin());
            Cob_jornadafin.setSelectedItem(v.getJornadaFin());
            TxfResultado_Visita.setText(v.getResultado());
            TxfPartes_Pendiente.setText(v.getPendiente() == null ? "" : v.getPendiente());
            Dap_Proxima_Visita.setDate(v.getDiaProxima());
            TmpHora_Prox.setTime(v.getHoraProxima());
        } catch (SQLException | NumberFormatException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo cargar la visita:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            javax.swing.SwingUtilities.invokeLater(this::dispose);
        }
    }

    /** Valida y guarda (agrega o modifica según el modo). */
    private void guardar() {
        if (idHogar == null) {
            JOptionPane.showMessageDialog(this, "Abra esta ventana desde un hogar.",
                    "Guardar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        LocalDate fecha = Dap_fechavisita.getDate();
        LocalTime inicio = Tmp_iniciovisita.getTime();
        LocalTime fin = Tmp_finvisita.getTime();
        LocalDate diaProxima = Dap_Proxima_Visita.getDate();
        LocalTime horaProxima = TmpHora_Prox.getTime();
        String resultado = TxfResultado_Visita.getText().trim();
        String pendiente = TxfPartes_Pendiente.getText().trim();

        // En la base de datos todas estas columnas son obligatorias (NOT NULL)
        if (fecha == null || inicio == null || fin == null || diaProxima == null
                || horaProxima == null || resultado.isEmpty() || pendiente.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Complete todos los campos del formulario.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (fin.isBefore(inicio)) {
            JOptionPane.showMessageDialog(this,
                    "La hora de fin no puede ser anterior a la hora de inicio.",
                    "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (resultado.length() > 20 || pendiente.length() > 100) {
            JOptionPane.showMessageDialog(this,
                    "El resultado admite máximo 20 caracteres y las personas/partes pendientes 100.",
                    "Texto muy largo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        ControlVisita v = new ControlVisita();
        v.setIdHogar(idHogar);
        v.setFecha(fecha);
        v.setHoraInicio(inicio);
        v.setJornadaInicio((String) Cob_inciovisita.getSelectedItem());
        v.setHoraFin(fin);
        v.setJornadaFin((String) Cob_jornadafin.getSelectedItem());
        v.setResultado(resultado);
        v.setPendiente(pendiente);
        v.setDiaProxima(diaProxima);
        v.setHoraProxima(horaProxima);

        try {
            if (numVisitaEditar == null) {
                dao.agregar(v);
                JOptionPane.showMessageDialog(this, "Visita " + v.getNumVisita() + " guardada correctamente.");
            } else {
                v.setNumVisita(Integer.parseInt(numVisitaEditar));
                dao.modificar(v);
                JOptionPane.showMessageDialog(this, "Visita " + numVisitaEditar + " modificada correctamente.");
            }
            dispose();   // windowClosed refresca la lista y la muestra
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo guardar:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

