    /** Llena el formulario con la comida a modificar. */
    private void cargarDatos() {
        try {
            ComidaFuera c = dao.buscar(idHogar, Integer.parseInt(numOrdenEditar));
            if (c == null) {
                JOptionPane.showMessageDialog(this, "No se encontró la comida " + numOrdenEditar + ".");
                dispose();
                return;
            }
            TxfDescripcion.setText(c.getDescripcion());
            RdbDesayuno.setSelected(ComidaFuera.DESAYUNO.equals(c.getTipoComida()));
            RdbAlmuerzo.setSelected(ComidaFuera.ALMUERZO.equals(c.getTipoComida()));
            RdbCena.setSelected(ComidaFuera.CENA.equals(c.getTipoComida()));
            RdbOnces.setSelected(ComidaFuera.ONCES.equals(c.getTipoComida()));
            SpiCantidad.setValue(c.getCantidad());
            CobForma_Adquisicion.setSelectedIndex(indiceDe(ID_FORMA, c.getIdFormaAdquisicion()));
            CobLugar_Compra.setSelectedIndex(indiceDe(ID_LUGAR, c.getIdLugarCompra()));
            SpiValor_Compra.setValue((int) Math.min(c.getCosto(), Integer.MAX_VALUE));
            CobFrecuencia.setSelectedIndex(indiceDe(ID_FRECUENCIA, c.getIdFrecuencia()));
            RdbHogar.setSelected("1".equals(c.getTipoGasto()));
            RdbPersonal.setSelected("2".equals(c.getTipoGasto()));
            ChbDomicilio.setSelected(c.isDomicilio());
        } catch (SQLException | NumberFormatException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar los datos:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            dispose();
        }
    }

    /** Valida el formulario y guarda (agregar o modificar según el modo). */
    private void guardar() {
        if (idHogar == null) {
            JOptionPane.showMessageDialog(this, "Abra esta ventana desde un hogar.",
                    "Guardar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            SpiCantidad.commitEdit();     // por si escribió el número y no presionó Enter
            SpiValor_Compra.commitEdit();
        } catch (java.text.ParseException ex) {
            JOptionPane.showMessageDialog(this, "Revise la cantidad y el valor pagado.",
                    "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String descripcion = TxfDescripcion.getText().trim();
        int cantidad = ((Number) SpiCantidad.getValue()).intValue();
        long costo = ((Number) SpiValor_Compra.getValue()).longValue();

        String tipoComida = RdbDesayuno.isSelected() ? ComidaFuera.DESAYUNO
                : RdbAlmuerzo.isSelected() ? ComidaFuera.ALMUERZO
                : RdbCena.isSelected() ? ComidaFuera.CENA
                : RdbOnces.isSelected() ? ComidaFuera.ONCES : null;
        String tipoGasto = RdbHogar.isSelected() ? "1"
                : RdbPersonal.isSelected() ? "2" : null;

        if (descripcion.isEmpty() || tipoComida == null || tipoGasto == null) {
            JOptionPane.showMessageDialog(this,
                    "Complete la descripción, el tipo de comida y el tipo de gasto.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad adquirida debe ser mayor que 0.",
                    "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (costo <= 0) {
            JOptionPane.showMessageDialog(this, "Indique cuánto pagó o tendría que pagar (mayor que 0).",
                    "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (descripcion.length() > 100) {
            JOptionPane.showMessageDialog(this, "La descripción admite máximo 100 caracteres.",
                    "Texto muy largo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idForma = idDe(ID_FORMA, CobForma_Adquisicion.getSelectedIndex());
        String idLugar = idDe(ID_LUGAR, CobLugar_Compra.getSelectedIndex());
        String idFrecuencia = idDe(ID_FRECUENCIA, CobFrecuencia.getSelectedIndex());
        if (idForma == null || idLugar == null || idFrecuencia == null) {
            JOptionPane.showMessageDialog(this,
                    "Una de las listas no coincide con los códigos de la base de datos.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        ComidaFuera c = new ComidaFuera();
        c.setIdHogar(idHogar);
        c.setDescripcion(descripcion);
        c.setTipoComida(tipoComida);
        c.setCantidad(cantidad);
        c.setIdFormaAdquisicion(idForma);
        c.setIdLugarCompra(idLugar);
        c.setCosto(costo);
        c.setIdFrecuencia(idFrecuencia);
        c.setTipoGasto(tipoGasto);
        c.setDomicilio(ChbDomicilio.isSelected());

        try {
            if (numOrdenEditar == null) {
                dao.agregar(c);
                JOptionPane.showMessageDialog(this, "Comida guardada correctamente.");
            } else {
                c.setNumOrden(Integer.parseInt(numOrdenEditar));
                dao.modificar(c);
                JOptionPane.showMessageDialog(this, "Cambios guardados correctamente.");
            }
            dispose();   // dispara windowClosed -> vuelve a la lista y la refresca
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "No se pudo guardar:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private static String idDe(String[] ids, int indice) {
        return (indice >= 0 && indice < ids.length) ? ids[indice] : null;
    }

    private static int indiceDe(String[] ids, String id) {
        for (int i = 0; i < ids.length; i++) {
            if (ids[i].equals(id)) {
                return i;
            }
        }
        return 0;
    }

